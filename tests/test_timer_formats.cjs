const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync('static/arena-banner.js','utf8'),ctx);
const fmt=vm.runInContext('iceBannerTime',ctx);
const seconds=5*86400+20*3600+28*60+1;
assert.equal(fmt(seconds,'hh:mm:ss'),'140:28:01');
assert.equal(fmt(seconds,'days'),'5д 20:28:01');
assert.equal(fmt(seconds,'dhms'),'5д 20ч 28м 01с');
assert.equal(fmt(seconds,'dhms-en'),'5D 20H 28M 01S');
assert.equal(fmt(seconds,'dhm-en'),'5D 20H 28M');
assert.equal(fmt(seconds,'hms-en'),'140H 28M 01S');
assert.equal(fmt(seconds,'days-only'),'5 дн');
assert.equal(fmt(seconds,'hours-only'),'140 ч');
assert.equal(fmt(seconds,'minutes-only'),'8428 мин');
assert.equal(fmt(seconds,'seconds-only'),'505681 с');
assert.equal(fmt(0,'dhms-en'),'0D 00H 00M 00S');
const data=vm.runInContext('ICE_TIMER_FORMATS',ctx);
assert.equal(data.length,11);
const page=fs.readFileSync('event_pages.py','utf8');
const arena=fs.readFileSync('arena_banner.py','utf8');
for(const [key] of data){assert.ok(page.includes("'"+key+"'"));assert.ok(arena.includes("'"+key+"'"));}
const studio=fs.readFileSync('static/event-studio.js','utf8');
const admin=fs.readFileSync('static/events-admin.js','utf8');
assert.match(studio,/crafterOpenEventPrizes/);
assert.match(admin,/data-event-prizes/);
assert.match(admin,/prize_collection_/);
assert.match(admin,/prize_model_/);
console.log('Countdown formats and visible collection prize UI passed');
