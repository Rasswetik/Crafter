"""PostgreSQL connection with the row and transaction interface used by Crafter."""
import re


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    columns = tuple(column.name for column in (cursor.description or ()))
    return lambda values: Row(zip(columns, values))


class Postgres:
    def __init__(self, url):
        import psycopg

        self.connection = psycopg.connect(
            url, autocommit=True, row_factory=row_factory, connect_timeout=8,
            options='-c lock_timeout=10000',
        )
        self.transaction = None

    def __enter__(self):
        self.transaction = self.connection.transaction()
        self.transaction.__enter__()
        return self

    def __exit__(self, exc_type, value, traceback):
        transaction, self.transaction = self.transaction, None
        return transaction.__exit__(exc_type, value, traceback)

    @staticmethod
    def bind(statement):
        return statement.replace('%', '%%').replace('?', '%s')

    def execute(self, statement, params=()):
        if statement == 'BEGIN IMMEDIATE':
            # Match SQLite's serialized read-modify-write transactions across workers.
            return self.connection.execute('SELECT pg_advisory_xact_lock(374516891)')
        if params:
            return self.connection.execute(self.bind(statement), params)
        return self.connection.execute(statement)

    def executemany(self, statement, rows):
        with self.connection.cursor() as cursor:
            cursor.executemany(self.bind(statement), rows)

    def executescript(self, script):
        with self.connection.transaction():
            self.connection.execute('SELECT pg_advisory_xact_lock(374516891)')
            for statement in script.split(';'):
                statement = statement.strip()
                if statement:
                    statement = re.sub(r'\bINTEGER\b', 'BIGINT', statement)
                    if statement.startswith('CREATE TABLE IF NOT EXISTS audit('):
                        statement = statement.replace('id BIGINT PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 1)
                    self.connection.execute(statement)
            for table in ('history', 'ton_deposits', 'ton_withdrawals'):
                self.connection.execute(
                    f'ALTER TABLE IF EXISTS {table} ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY'
                )

    def commit(self):
        # Statements outside a with-block already commit individually.
        if self.transaction is not None:
            raise RuntimeError('Use the transaction context to commit PostgreSQL writes')

    def close(self):
        self.connection.close()
